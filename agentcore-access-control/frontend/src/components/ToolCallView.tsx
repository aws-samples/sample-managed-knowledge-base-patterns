import Alert from "@cloudscape-design/components/alert";
import Box from "@cloudscape-design/components/box";
import ExpandableSection from "@cloudscape-design/components/expandable-section";
import SpaceBetween from "@cloudscape-design/components/space-between";
import StatusIndicator from "@cloudscape-design/components/status-indicator";
import {
	documentName,
	requestedUserId,
	type ToolCall,
} from "../agent/conversation";

const STATUS = {
	running: { type: "loading", text: "Running" },
	success: { type: "success", text: "Completed" },
	error: { type: "error", text: "Failed" },
} as const;

interface ToolCallViewProps {
	call: ToolCall;
	/** Verified email of the signed-in user. */
	email: string;
}

/**
 * Shows the tool arguments that the LLM generated next to the documents
 * that the gateway returned, so that a spoofed userContext and its effect
 * (none) are visible side by side.
 */
export function ToolCallView({ call, email }: ToolCallViewProps) {
	const requested = requestedUserId(call.input);
	const spoofed = requested !== undefined && requested !== email;
	const status = STATUS[call.status];

	return (
		<ExpandableSection
			variant="stacked"
			defaultExpanded={spoofed}
			headerText={call.name}
			headerInfo={
				<StatusIndicator type={status.type}>{status.text}</StatusIndicator>
			}
		>
			<SpaceBetween size="s">
				{spoofed ? (
					<Alert
						type="warning"
						header="The agent requested another user's identity"
					>
						The agent set{" "}
						<Box variant="awsui-inline-code">userContext.userId</Box> to{" "}
						{requested}. The gateway interceptor overwrites it with your
						verified email ({email}) before the search.
					</Alert>
				) : (
					<Box variant="small" color="text-body-secondary">
						The gateway interceptor sets{" "}
						<Box variant="awsui-inline-code">userContext.userId</Box> to your
						verified email ({email}), whatever the agent sends.
					</Box>
				)}
				<div>
					<Box variant="awsui-key-label">Arguments generated by the agent</Box>
					<Box variant="pre" fontSize="body-s">
						{JSON.stringify(call.input, null, 2)}
					</Box>
				</div>
				{call.status !== "running" && (
					<div>
						<Box variant="awsui-key-label">Documents returned</Box>
						{call.sources.length > 0 ? (
							<ul>
								{call.sources.map((uri) => (
									<li key={uri}>{documentName(uri)}</li>
								))}
							</ul>
						) : (
							<Box color="text-body-secondary">No documents</Box>
						)}
					</div>
				)}
				{call.resultText && (
					<ExpandableSection variant="footer" headerText="Raw tool result">
						<Box variant="pre" fontSize="body-s">
							{call.resultText}
						</Box>
					</ExpandableSection>
				)}
			</SpaceBetween>
		</ExpandableSection>
	);
}
